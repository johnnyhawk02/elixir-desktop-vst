// Writes Source/LxrTables.h from Elixir Desktop's engine modules (lxr-tables.js, lxr-clicks.js, lxr-ui-data.js),
// so the C++ engine uses exactly the same tables and parameter numbers as the app.
//   node tools/gen-tables.mjs [path to elixir-desktop, default ~/Developer/elixir-desktop]
// Reads the app's files only; never writes there.
import { writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { pathToFileURL } from 'node:url';
import { join } from 'node:path';

const src = process.argv[2] || join(homedir(), 'Developer/elixir-desktop');
const load = (f) => import(pathToFileURL(join(src, f)).href);
const T = await load('lxr-tables.js');
const C = await load('lxr-clicks.js');
const U = await load('lxr-ui-data.js');

const arr = (type, name, a, per = 24) => {
  const v = Array.from(a, (x) => (type === 'float' ? (Number.isInteger(x) ? `${x}.0f` : `${x}f`) : String(x)));
  const rows = [];
  for (let i = 0; i < v.length; i += per) rows.push('  ' + v.slice(i, i + per).join(','));
  return `static const ${type} ${name}[${v.length}] = {\n${rows.join(',\n')}\n};\n`;
};
const consts = (ns, o) => `namespace ${ns} {\n${Object.entries(o).map(([k, v]) => `  constexpr int ${k} = ${v};`).join('\n')}\n}\n`;

// MIDI_NOTE_FREQ is a Float32Array: print each value with enough digits to round-trip as a float
const f32 = (a) => Array.from(a, (x) => Number(x.toPrecision(9)));

let out = `// Generated by tools/gen-tables.mjs from Elixir Desktop's lxr-tables.js, lxr-clicks.js and lxr-ui-data.js.
// Don't edit; rerun the generator. GPL-3.0-only, like the LXR firmware the tables come from.
#pragma once
#include <cstdint>

namespace lxr {
`;
out += consts('PAR', T.PAR) + consts('CC', T.CC) + consts('CC2', T.CC2);
out += arr('int16_t', 'SINE_TABLE', T.SINE_TABLE);
out += arr('int16_t', 'TRI_TABLE', T.TRI_TABLE);
out += arr('int16_t', 'REC_TABLE', T.REC_TABLE);
out += arr('int16_t', 'SAW_TABLE', T.SAW_TABLE);
out += arr('int8_t', 'TRANSIENT_DATA', T.TRANSIENT_DATA, 32);
out += arr('float', 'MIDI_NOTE_FREQ', f32(T.MIDI_NOTE_FREQ), 8);
out += arr('uint8_t', 'INIT_KIT', T.INIT_KIT, 32);
out += arr('uint8_t', 'PARAMETER_ORDER', T.PARAMETER_ORDER, 32);
// the velocity / LFO target menu: index -> parameter number
out += arr('uint16_t', 'MOD_TARGET_PAR', U.MOD_TARGETS.map((t) => t[1]), 24);
C.EXTRA_CLICKS.forEach((c, i) => { out += arr('int16_t', `EXTRA_CLICK_${i}`, c); });
out += `struct Click { const int16_t* data; int length; };\nstatic const Click EXTRA_CLICKS[${C.EXTRA_CLICKS.length}] = {\n${C.EXTRA_CLICKS.map((c, i) => `  { EXTRA_CLICK_${i}, ${c.length} }`).join(',\n')}\n};\n`;
out += `constexpr int NUM_EXTRA_CLICKS = ${C.EXTRA_CLICKS.length};\n`;
// lxr.js itself: the modulatable-parameter set and the FX tables it keeps inline
const L = await load('lxr.js');
const mod = new Uint8Array(T.PAR.NUM_PARAMS);
for (const p of L.MODULATABLE) mod[p] = 1;
out += arr('uint8_t', 'MODULATABLE', mod, 48);
const text = (await import('node:fs')).readFileSync(join(src, 'lxr.js'), 'utf8');
for (const [name, type] of [['TABLE_1N914', 'float'], ['ECC83_TABLE', 'double'], ['EXP2F_TAB_HI', 'uint32_t'], ['EXP2F_TAB_LO', 'uint32_t'],
  ['LOGF_INVC', 'double'], ['LOGF_LOGC', 'double']]) {
  const m = new RegExp(`const ${name} = new \\w+\\(\\[([\\s\\S]*?)\\]\\)`).exec(text);
  if (!m) throw new Error(`lxr.js: ${name} not found`);
  const vals = m[1].split(',').map((s) => s.trim()).filter(Boolean);
  out += `static const ${type} ${name}[${vals.length}] = {\n  ${vals.map((v) => (type === 'float' ? `${v}f` : type === 'uint32_t' ? `${v}u` : v)).join(', ')}\n};\n`;
}
out += '}\n';

const dst = new URL('../Source/LxrTables.h', import.meta.url);
writeFileSync(dst, out);
console.log(`Source/LxrTables.h: ${(out.length / 1024).toFixed(0)} KB`);
